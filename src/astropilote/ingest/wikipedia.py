"""English Wikipedia article fetcher with batch MediaWiki API queries and local caching."""

from __future__ import annotations

import asyncio
import json
from pathlib import Path

import httpx

from astropilote.ingest.catalog import CatalogTarget

WIKIPEDIA_API_URL = "https://en.wikipedia.org/w/api.php"
USER_AGENT = (
    "AstroPilote-Albert School × Mines Paris-Project/0.1 (https://github.com/astropilote; academic RAG research)"
)


def _cache_path(wiki_cache_dir: Path, doc_id: str) -> Path:
    return wiki_cache_dir / f"{doc_id}.json"


def is_synthetic_fallback(extract: str) -> bool:
    """Detect whether a cached extract was generated by `build_fallback_extract`."""
    return "== Observation & Astrophotography ==\nAt J2000 coordinates RA" in extract


def build_fallback_extract(target: CatalogTarget) -> str:
    """Synthesize a factual structured summary if a Wikipedia article is missing or offline."""
    size_str = (
        f"{target.size_major_arcmin}' x {target.size_minor_arcmin}'"
        if target.size_major_arcmin and target.size_minor_arcmin
        else (
            f"{target.size_major_arcmin}'"
            if target.size_major_arcmin
            else "compact angular size"
        )
    )
    mag_str = (
        f"visual magnitude {target.magnitude}"
        if target.magnitude is not None
        else "moderate brightness"
    )
    nb_note = (
        "Because it is an ionized emission or planetary nebula, it responds strongly to narrowband "
        "H-alpha, OIII, and dual-band astrophotography filters even under moderate moonlight, and "
        "benefits from UHC or OIII filters in visual astronomy."
        if target.narrowband_friendly
        else "As a broadband continuum target, it is best observed and imaged during dark, moonless windows."
    )
    return (
        f"{target.title} ({target.doc_id}) is a {target.object_type.replace('_', ' ')} located in the "
        f"constellation {target.constellation} with {mag_str} and an angular size of {size_str}. "
        f"Known designations include {', '.join(target.aliases)}.\n\n"
        f"== Observation & Astrophotography ==\n"
        f"At J2000 coordinates RA {target.ra_deg}° and Dec {target.dec_deg}°, {target.title} is "
        f"cataloged in the {target.catalog} collection. {nb_note}\n\n"
        f"== Physical Characteristics ==\n"
        f"{target.title} exhibits structural morphology characteristic of a {target.object_type.replace('_', ' ')} "
        f"in {target.constellation}, spanning {size_str} with {mag_str}.\n\n"
        f"== Astrometry & Cross-Identifications ==\n"
        f"Cross-catalog identifiers for {target.doc_id} include {', '.join(target.aliases)} "
        f"(Right Ascension {target.ra_deg}°, Declination {target.dec_deg}°)."
    )


async def _fetch_single(
    client: httpx.AsyncClient,
    semaphore: asyncio.Semaphore,
    target: CatalogTarget,
    wiki_cache_dir: Path,
) -> tuple[str, str, str]:
    """Fetch a single Wikipedia extract by title with polite rate-limiting & 429 retry."""
    cache_file = _cache_path(wiki_cache_dir, target.doc_id)
    if cache_file.exists():
        data = json.loads(cache_file.read_text(encoding="utf-8"))
        existing_extract = data.get("extract", "")
        if existing_extract and not is_synthetic_fallback(existing_extract):
            return target.doc_id, data.get("title", target.title), existing_extract

    params = {
        "action": "query",
        "prop": "extracts",
        "explaintext": "1",
        "redirects": "1",
        "titles": target.wiki_query,
        "format": "json",
    }
    extract = ""
    resolved_title = target.title

    async with semaphore:
        for attempt in range(4):
            try:
                resp = await client.get(WIKIPEDIA_API_URL, params=params)
                if resp.status_code == 429:
                    await asyncio.sleep(1.5 * (attempt + 1))
                    continue
                resp.raise_for_status()
                payload = resp.json()
                pages = payload.get("query", {}).get("pages", {})
                for page_id, page_data in pages.items():
                    if page_id != "-1":
                        extract = page_data.get("extract", "") or ""
                        resolved_title = page_data.get("title", target.title)
                        break
                break
            except Exception:
                await asyncio.sleep(0.8 * (attempt + 1))

    if len(extract.strip()) < 80:
        # A guide cannot be synthesized from catalog numbers: leave it empty so the pipeline
        # skips it (and reports it) instead of indexing an invented text.
        extract = "" if target.catalog == "Guide" else build_fallback_extract(target)

    cache_file.write_text(
        json.dumps(
            {
                "doc_id": target.doc_id,
                "wiki_query": target.wiki_query,
                "title": resolved_title,
                "extract": extract,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    return target.doc_id, resolved_title, extract


async def fetch_wikipedia_corpus_async(
    targets: list[CatalogTarget],
    wiki_cache_dir: Path,
    concurrency: int = 5,
) -> dict[str, tuple[str, str]]:
    """Concurrently fetch and cache English Wikipedia plain-text extracts for all targets."""
    wiki_cache_dir.mkdir(parents=True, exist_ok=True)
    semaphore = asyncio.Semaphore(concurrency)
    headers = {"User-Agent": USER_AGENT}
    results: dict[str, tuple[str, str]] = {}

    async with httpx.AsyncClient(headers=headers, timeout=25.0, follow_redirects=True) as client:
        tasks = [_fetch_single(client, semaphore, t, wiki_cache_dir) for t in targets]
        for doc_id, resolved_title, extract in await asyncio.gather(*tasks):
            results[doc_id] = (resolved_title, extract)

    return results
