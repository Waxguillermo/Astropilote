"""Local natural-language AstroPilote MCP CLI (`api`, `local`, or `offline` mode)."""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from astropilote.agentic.llm_agent import LLMObservatoryAgent
from astropilote.agentic.memory_conversation import MemoryConversationalAgent
from astropilote.config import settings
from astropilote.llm import _refresh_env_settings
from astropilote.tracing import setup_tracing


def main() -> None:
    parser = argparse.ArgumentParser(
        description="AstroPilote natural-language observatory & sky MCP agent"
    )
    parser.add_argument("--text", required=True, help="French or English user request")
    parser.add_argument("--user", required=True, help="Trusted local operator user ID")
    parser.add_argument("--thread", help="LangGraph thread ID (auto-generated by default)")
    parser.add_argument("--db", default="data/backend/observatory.sqlite3")
    parser.add_argument("--checkpoints", default="data/backend/agentic_checkpoints.sqlite3")
    parser.add_argument("--memory-db", default="data/backend/user_memory.sqlite3")
    parser.add_argument(
        "--llm-mode",
        choices=["api", "local", "offline"],
        default=None,
        help="Planner mode: 'api' (Claude), 'local' (Ollama Gemma 4), or 'offline' (deterministic).",
    )
    parser.add_argument(
        "--date", type=date.fromisoformat, help="Reference date YYYY-MM-DD for deterministic runs"
    )
    parser.add_argument("--max-steps", type=int, default=6)
    args = parser.parse_args()
    setup_tracing()
    if not Path(args.db).is_file():
        parser.error(
            "Backend absent : initialiser avec uv run python -m astropilote.backend.store --seed seeds/observatory_demo.json"
        )
    _refresh_env_settings()
    mode = args.llm_mode or ("api" if settings.anthropic_api_key.strip() else "offline")
    if mode in ("api", "local"):
        with LLMObservatoryAgent(
            db_path=args.db,
            checkpoint_path=args.checkpoints,
            memory_path=args.memory_db,
            llm_mode=mode,
        ) as agent:
            result = agent.handle(
                args.text,
                user_id=args.user,
                thread_id=args.thread,
                reference_date=args.date,
                max_steps=args.max_steps,
            )
    else:
        result = MemoryConversationalAgent(
            db_path=args.db,
            checkpoint_path=args.checkpoints,
            memory_path=args.memory_db,
        ).handle(
            args.text,
            user_id=args.user,
            thread_id=args.thread,
            reference_date=args.date,
            max_steps=args.max_steps,
        )
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
