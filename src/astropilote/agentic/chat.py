"""Local natural-language AstroPilote CLI; approval remains operator-only.

Example:
    uv run python -m astropilote.agentic.chat --user astro-club --text 'Annule BK-001'
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from astropilote.agentic.conversation import ConversationalAgent


def main() -> None:
    parser = argparse.ArgumentParser(description="AstroPilote local conversational MCP router")
    parser.add_argument("--text", required=True, help="French or English user request")
    parser.add_argument("--user", required=True, help="Trusted local operator user ID")
    parser.add_argument("--thread", help="Fresh LangGraph thread ID (auto-generated by default)")
    parser.add_argument("--db", default="data/backend/observatory.sqlite3")
    parser.add_argument("--checkpoints", default="data/backend/agentic_checkpoints.sqlite3")
    parser.add_argument("--date", type=date.fromisoformat, help="Reference date YYYY-MM-DD for deterministic demos")
    parser.add_argument("--max-steps", type=int, default=5)
    args = parser.parse_args()
    if not Path(args.db).is_file():
        parser.error("Backend absent : initialiser avec uv run python -m astropilote.backend.store --seed seeds/observatory_demo.json")
    result = ConversationalAgent(db_path=args.db, checkpoint_path=args.checkpoints).handle(
        args.text, user_id=args.user, thread_id=args.thread,
        reference_date=args.date, max_steps=args.max_steps,
    )
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
